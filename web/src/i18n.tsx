const dicts: Record<Lang, Record<Key, string>> = { en, ru };

/** Plural forms by Intl.PluralRules category. */
const nouns = {
  task: { en: { one: 'task', other: 'tasks' }, ru: { one: 'задача', few: 'задачи', many: 'задач', other: 'задачи' } },
  doc: { en: { one: 'document', other: 'documents' }, ru: { one: 'документ', few: 'документа', many: 'документов', other: 'документа' } },
  comment: { en: { one: 'comment', other: 'comments' }, ru: { one: 'комментарий', few: 'комментария', many: 'комментариев', other: 'комментария' } },
  line: { en: { one: 'line', other: 'lines' }, ru: { one: 'строка', few: 'строки', many: 'строк', other: 'строки' } },
  todo: { en: { one: 'todo', other: 'todos' }, ru: { one: 'дело', few: 'дела', many: 'дел', other: 'дела' } },
} as const;
export type Noun = keyof typeof nouns;

export type T = (key: Key, vars?: Record<string, string | number>) => string;

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: T;
  /** "3 comments" / "3 комментария". */
  count: (n: number, noun: Noun) => string;
  /** "5 minutes ago" / "5 минут назад", or a date when older than a week. */
  ago: (iso: string) => string;
  date: (iso: string) => string;
  dateTime: (iso: string) => string;
}

const Ctx = createContext<I18n | null>(null);

function initialLang(): Lang {
  const saved = load('lang');
  if (saved === 'en' || saved === 'ru') return saved;
  return navigator.language?.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const value = useMemo<I18n>(() => {
    const dict = dicts[lang];
    const t: T = (key, vars) => {
      let s = dict[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    };
    const rtf = new Intl.RelativeTimeFormat(lang, { numeric: 'auto', style: 'long' });
    const df = new Intl.DateTimeFormat(lang, { day: 'numeric', month: 'short', year: 'numeric' });
    const dtf = new Intl.DateTimeFormat(lang, { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' });
    const ago = (iso: string) => {
      const s = (Date.now() - new Date(iso).getTime()) / 1000;
      if (s < 60) return t('ago.now');
      if (s < 3600) return rtf.format(-Math.round(s / 60), 'minute');
      if (s < 86400) return rtf.format(-Math.round(s / 3600), 'hour');
      if (s < 7 * 86400) return rtf.format(-Math.round(s / 86400), 'day');
      return df.format(new Date(iso));
    };
    const pr = new Intl.PluralRules(lang);
    const count = (n: number, noun: Noun) => {
      const forms = nouns[noun][lang] as Record<string, string>;
      return `${n} ${forms[pr.select(n)] ?? forms.other}`;
    };
    return {
      lang,
      count,
      setLang: (l) => {
        save('lang', l);
        document.documentElement.lang = l;
        setLangState(l);
      },
      t,
      ago,
      date: (iso) => df.format(new Date(iso)),
      dateTime: (iso) => dtf.format(new Date(iso)),
    };
  }, [lang]);
  document.documentElement.lang = lang;
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n outside I18nProvider');
  return v;
}
